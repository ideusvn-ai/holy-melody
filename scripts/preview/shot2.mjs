import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const [fixture, out] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:8765/');
await page.setInputFiles('input[type=file]', fixture);
await page.waitForTimeout(500);
await page.click('role=tab[name="SCORE EDITOR"]');
await page.waitForTimeout(500);
await page.click('role=tab[name="Hợp âm"]');
await page.click('text=Gợi ý hợp âm');
await page.waitForTimeout(300);
await page.screenshot({ path: 'dbg.png' }); console.log(await page.locator('[role=status]').allTextContents()); await page.locator('section[aria-label="Gợi ý hợp âm"] li').nth(1).click({ timeout: 3000 });
await page.waitForTimeout(500);
await page.screenshot({ path: out });
console.log(JSON.stringify({ variants: await page.locator('section[aria-label="Gợi ý hợp âm"] li').count(), errors }));
await browser.close();
