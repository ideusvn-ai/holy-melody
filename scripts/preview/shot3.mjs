import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const [fixture, out] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:8765/');
await page.setInputFiles('input[type=file]', fixture);
await page.waitForTimeout(400);
await page.click('role=tab[name="SCORE EDITOR"]');
await page.click('role=tab[name="Lời ca"]');
await page.selectOption('section[aria-label="Lời ca"] select >> nth=1', '2');
await page.fill('textarea[aria-label="Lời 2"]', 'Lòng con tín thác nơi Chúa _ hiền, dẫn đưa đoàn con qua bao tháng ngày, A-men');
await page.waitForTimeout(200);
const report = await page.locator('section[aria-label="Lời ca"] div.rounded-md.px-2').first().textContent();
await page.click('text=Gán lời vào nốt');
await page.waitForTimeout(300);
await page.selectOption('section[aria-label="Lời ca"] select >> nth=2', 'Times New Roman');
await page.waitForTimeout(300);
await page.screenshot({ path: out });
console.log(JSON.stringify({ report, errors }));
await browser.close();
