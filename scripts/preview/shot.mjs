import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const fixture = process.argv[2];
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()));
await page.goto('http://localhost:8765/');
await page.waitForSelector('text=Holy Melody');
await page.setInputFiles('input[type=file]', fixture);
await page.waitForTimeout(600);
await page.click('button[aria-label="Phát"]');
await page.waitForTimeout(2200);
const playing = await page.locator('.hm-playing').count();
await page.screenshot({ path: 'player.png' });
await page.keyboard.press('Space');
await page.click('role=tab[name="SCORE EDITOR"]');
await page.waitForTimeout(700);
// chọn nốt đầu tiên và đổi cao độ bằng phím
await page.locator('.hm-note').first().click();
await page.keyboard.press('ArrowUp');
await page.waitForTimeout(400);
const advisorCount = await page.locator('section[aria-label="Trợ lý soạn nhạc"] li').count();
await page.screenshot({ path: 'editor.png' });
await page.keyboard.press(process.platform === 'darwin' ? 'Meta+z' : 'Control+z');
await page.click('role=tab[name="AI SINGER"]');
await page.waitForTimeout(400);
await page.screenshot({ path: 'singer.png' });
await page.evaluate(() => (document.documentElement.dataset.theme = 'dark'));
await page.click('role=tab[name="PLAYER"]');
await page.waitForTimeout(400);
await page.screenshot({ path: 'player-dark.png' });
console.log(JSON.stringify({ playing, advisorCount, errors }, null, 1));
await browser.close();
