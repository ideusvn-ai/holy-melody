import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const [fixture] = process.argv.slice(2);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://localhost:8765/');
await page.setInputFiles('input[type=file]', fixture);
await page.waitForTimeout(400);
await page.evaluate(() => { window.print = () => {}; });
await page.keyboard.press('Control+p');
await page.waitForTimeout(300);
const pages = await page.locator('#hm-print .hm-page').count();
await page.pdf({ path: 'score.pdf', preferCSSPageSize: true, printBackground: true });
await page.emulateMedia({ media: 'print' });
await page.setViewportSize({ width: 794, height: 1123 });
await page.screenshot({ path: 'print-p1.png' });
console.log(JSON.stringify({ pages, errors }));
await browser.close();
